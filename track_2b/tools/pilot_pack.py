"""Pilotpaket Phase 1, Variante A: eine ZIP-Datei mit Prüfsummen, reproduzierbar (gleicher Commit -> gleiche Bytes).

  python3 tools/pilot_pack.py              prüft Fallblätter und PDFs auf Aktualität, baut das Register offline und schreibt
                                           dist/gleichlaut-pilot-phase1-<SL-Stand>.zip und .zip.sha256 (dist/ ist
                                           gitignoriert; die ZIP-Datei wird nicht eingecheckt)
  python3 tools/pilot_pack.py --out DIR    schreibt nach DIR
  python3 tools/pilot_pack.py --readme     schreibt zusätzlich die erwartete sha256 der ZIP-Datei in docs/pilot/README.md
  python3 tools/pilot_pack.py --check      baut das Paket im Speicher und prüft, dass seine sha256 der in docs/pilot/README.md
                                           entspricht (exit 1 sonst; schreibt nichts)

Inhalt (Pfade wie in docs/pilot/, damit die Links der Dokumente gelten):
  Entscheidvorlage_Phase1.md, Management_Notiz.md, Projektauftrag_Phase1.md, Schutzbedarfsanalyse_Phase1.md
  fallblaetter/*.md                        die Fallblätter (tools/pilot_sheets.py) mit Übersicht
  pdf/*.pdf                                Entscheidvorlage, Management-Notiz und Fallblätter als PDF (tools/pilot_pdf.py)
  register/gleichlaut-register.html        das Register als eine Datei, offline lesbar (ohne Netz, ohne Server)
  SHA256SUMS                               sha256 jeder Datei im Paket (`shasum -a 256 -c SHA256SUMS` im entpackten Ordner)
Reproduzierbar: gleicher Inhalt -> gleiche Bytes, unabhängig von Commit, Uhrzeit und Rechner: feste Reihenfolge, fester
Zeitstempel (der SL-Stand, 06.10.2026 00:00), feste Rechte, feste Kompression; die Code-Revision im Register ist ein
Inhaltshash von src/ («src-…»), nicht der Commit. Deshalb kann die erwartete sha256 der ZIP-Datei im Repositorium stehen
(docs/pilot/README.md, geprüft mit --check und tests/test_pilot_sheets.py): wer das Paket erhält, baut es aus demselben
Commit neu und vergleicht. Keine Modellaufrufe, kein Netz."""
import glob, hashlib, io, os, sys, zipfile

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
sys.path.insert(0, os.path.join(ROOT, "src")); sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
PILOT = os.path.join(ROOT, "docs", "pilot")
DOCS = ("Entscheidvorlage_Phase1.md", "Management_Notiz.md", "Projektauftrag_Phase1.md", "Schutzbedarfsanalyse_Phase1.md")


README = os.path.join(PILOT, "README.md")
MARK = ("<!-- pilot-pack-sha256: generated by tools/pilot_pack.py --readme, checked by --check -->", "<!-- /pilot-pack-sha256 -->")


def stamp(date):
    """The zip entries' time: the SL snapshot date of the pack (00:00), so the bytes depend on the content only, not on
    the commit or the clock (a commit time would change the hash with every commit, also of the README that records it)."""
    return (int(date[:4]), int(date[4:6]), int(date[6:8]), 0, 0, 0) if date and len(date) == 8 and date.isdigit() else (1980, 1, 1, 0, 0, 0)


def src_rev():
    """The register's code revision inside the pack: 'src-' + the first 8 hex of a sha256 over every file under src/
    (path and bytes; no caches, no dot files, no *.egg-info of `pip install -e .`). Content-addressed like the rest of the pack, unlike the commit hash."""
    h = hashlib.sha256(); base = os.path.join(ROOT, "src")
    for d, ds, fs in os.walk(base):
        ds[:] = sorted(x for x in ds if x != "__pycache__" and not x.startswith(".") and not x.endswith(".egg-info"))   # not pip -e output
        for f in sorted(fs):
            if f.startswith(".") or f.endswith((".pyc", ".pyo")): continue
            p = os.path.join(d, f); h.update(os.path.relpath(p, base).replace(os.sep, "/").encode() + b"\0" + open(p, "rb").read() + b"\0")
    return "src-" + h.hexdigest()[:8]


def files():
    """{path in the pack: bytes}"""
    import pilot_pdf, pilot_sheets
    from gleichlaut.ui import audit_view, build
    if pilot_sheets.main(["--check"]) != 0: sys.exit("pilot_pack: docs/pilot/fallblaetter/ is not current (python3 tools/pilot_sheets.py)")
    if pilot_pdf.main(["--check"]) != 0: sys.exit("pilot_pack: docs/pilot/pdf/ is not current (make pilot-pdf)")
    F = {}
    for d in DOCS: F[d] = open(os.path.join(PILOT, d), "rb").read()
    for p in sorted(glob.glob(os.path.join(PILOT, "fallblaetter", "*.md"))): F["fallblaetter/" + os.path.basename(p)] = open(p, "rb").read()
    for p in sorted(glob.glob(os.path.join(PILOT, "pdf", "*.pdf"))): F["pdf/" + os.path.basename(p)] = open(p, "rb").read()
    import tempfile
    with tempfile.TemporaryDirectory(prefix="gl-pack-") as t:
        out = os.path.join(t, "register.html")
        old = os.environ.get("GIT_COMMIT"); os.environ["GIT_COMMIT"] = src_rev()
        try: build.build(out=out, hist=None)             # the bundled audit texts, as the published page: no snapshot files needed
        finally:
            if old is None: os.environ.pop("GIT_COMMIT", None)
            else: os.environ["GIT_COMMIT"] = old
        F["register/gleichlaut-register.html"] = open(out, "rb").read()
    F["SHA256SUMS"] = "".join(f"{hashlib.sha256(b).hexdigest()}  {k}\n" for k, b in sorted(F.items())).encode()
    return F


def pack(F, name, date):
    buf = io.BytesIO(); ts = stamp(date)
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as z:
        for k in ["SHA256SUMS"] + sorted(x for x in F if x != "SHA256SUMS"):
            zi = zipfile.ZipInfo(f"{name}/{k}", date_time=ts); zi.compress_type = zipfile.ZIP_DEFLATED
            zi.external_attr = 0o644 << 16; zi.create_system = 3
            z.writestr(zi, F[k], compresslevel=9)
    return buf.getvalue()


def recorded():
    """-> dict(zip, sha256, content, zlib) recorded in docs/pilot/README.md, or {}."""
    import re
    s = open(README, encoding="utf-8").read()
    if MARK[0] not in s or MARK[1] not in s: return {}
    b = s[s.index(MARK[0]):s.index(MARK[1])]
    g = lambda rx: (re.search(rx, b) or [None, None])[1]
    return dict(zip=g(r"ZIP-Datei \| `([\w.-]+\.zip)`"), sha256=g(r"sha256 der ZIP-Datei \| `([0-9a-f]{64})`"),
                content=g(r"sha256 von SHA256SUMS[^|]*\| `([0-9a-f]{64})`"), zlib=g(r"zlib ([\d.]+)"))


def state(name, F, z):
    import zlib
    return dict(zip=name + ".zip", sha256=hashlib.sha256(z).hexdigest(), content=hashlib.sha256(F["SHA256SUMS"]).hexdigest(),
                zlib=zlib.ZLIB_RUNTIME_VERSION)


def write_readme(st, n):
    s = open(README, encoding="utf-8").read()
    if MARK[0] not in s: raise SystemExit(f"pilot_pack: no {MARK[0]} block in {README}")
    block = (f"{MARK[0]}\n\n| Paket | erwarteter Wert |\n|---|---|\n| ZIP-Datei | `{st['zip']}` ({n} Dateien) |\n"
             f"| sha256 der ZIP-Datei | `{st['sha256']}` |\n| sha256 von SHA256SUMS (Inhalt aller Dateien) | `{st['content']}` |\n"
             f"| gebaut mit | Python zipfile, Deflate Stufe 9, zlib {st['zlib']} |\n\n{MARK[1]}")
    s = s[:s.index(MARK[0])] + block + s[s.index(MARK[1]) + len(MARK[1]):]
    open(README, "w", encoding="utf-8").write(s)


def check(st):
    """0 when this tree builds the recorded pack. The content (SHA256SUMS) must match; the zip bytes must match too, unless
    this Python links another zlib than the recorded one (Deflate output may differ between zlib builds): then the
    content decides and a note says so."""
    r = recorded()
    if r.get("zip") != st["zip"] or r.get("content") != st["content"]:
        print(f"pilot_pack --check: docs/pilot/README.md records {r.get('zip')} content {r.get('content')}; this tree builds "
              f"{st['zip']} content {st['content']} (python3 tools/pilot_pack.py --readme after a deliberate change)"); return 1
    if r.get("sha256") != st["sha256"]:
        if r.get("zlib") and r["zlib"] != st["zlib"]:
            print(f"ok (content): {st['zip']} has the recorded content; zip sha256 {st['sha256']} differs from the recorded "
                  f"{r['sha256']} because this Python links zlib {st['zlib']}, the record zlib {r['zlib']}"); return 0
        print(f"pilot_pack --check: zip sha256 {st['sha256']}, recorded {r.get('sha256')} (python3 tools/pilot_pack.py --readme)")
        return 1
    print(f"ok: {st['zip']} sha256 {st['sha256']} as recorded in docs/pilot/README.md"); return 0


def main(argv=None):
    a = sys.argv[1:] if argv is None else argv
    out = a[a.index("--out") + 1] if "--out" in a else os.path.join(ROOT, "dist")
    from gleichlaut.ui import audit_view
    import json
    date = json.load(open(audit_view.AUDIT, encoding="utf-8")).get("summary", {}).get("date") or "audit"
    name = f"gleichlaut-pilot-phase1-{date}"
    F = files(); z = pack(F, name, date); st = state(name, F, z); h = st["sha256"]
    if "--check" in a: return check(st)
    if "--readme" in a: write_readme(st, len(F))
    os.makedirs(out, exist_ok=True); p = os.path.join(out, name + ".zip")
    open(p, "wb").write(z)
    open(p + ".sha256", "w", encoding="utf-8").write(f"{h}  {name}.zip\n")
    print(f"{os.path.relpath(p, ROOT)}: {len(F)} files, {len(z) // 1024} KB, sha256 {h}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
